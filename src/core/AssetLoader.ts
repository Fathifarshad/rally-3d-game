import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import type { GLTF } from 'three/examples/jsm/loaders/GLTFLoader.js';

/**
 * Optional-asset pipeline.
 *
 * The game ships with a fully procedural car so it runs with an empty assets
 * folder. Drop a real model at /public/assets/models/nissan_z.glb and it is
 * detected here and swapped in automatically — same for audio files under
 * /public/assets/sounds/.
 */

export interface LoadedCarModel {
  scene: THREE.Group;
  wheels: THREE.Object3D[];
  steeringWheel: THREE.Object3D | null;
  paintMaterials: THREE.MeshStandardMaterial[];
}

const MODEL_FILE = 'nissan_z.glb';
const MODEL_URL = `assets/models/${MODEL_FILE}`;

interface AssetManifest {
  models: string[];
  sounds: string[];
}

let manifestPromise: Promise<AssetManifest> | null = null;

/**
 * Reads the manifest generated by the Vite plugin (see vite.config.ts).
 * Cached for the session and shared by every loader instance.
 */
function loadManifest(): Promise<AssetManifest> {
  if (!manifestPromise) {
    manifestPromise = fetch('assets/manifest.json', { cache: 'no-store' })
      .then((res) => (res.ok ? res.json() : null))
      .then((data: Partial<AssetManifest> | null) => ({
        models: data?.models ?? [],
        sounds: data?.sounds ?? [],
      }))
      .catch(() => ({ models: [], sounds: [] }));
  }
  return manifestPromise;
}

export class AssetLoader {
  private readonly gltfLoader = new GLTFLoader();

  onProgress: ((ratio: number, label: string) => void) | null = null;

  /** True when the file is listed in the generated asset manifest. */
  private async exists(url: string): Promise<boolean> {
    const manifest = await loadManifest();
    const [, folder, file] = url.split('/');
    const list = folder === 'models' ? manifest.models : manifest.sounds;
    return list.includes(file);
  }

  /** Returns the real Nissan Z model if the user supplied one, else null. */
  async loadCarModel(): Promise<LoadedCarModel | null> {
    this.onProgress?.(0.1, 'LOOKING FOR CAR MODEL…');
    if (!(await this.exists(MODEL_URL))) {
      this.onProgress?.(0.35, 'USING BUILT-IN Z MODEL');
      return null;
    }

    try {
      const gltf: GLTF = await this.gltfLoader.loadAsync(MODEL_URL, (e) => {
        if (e.total) this.onProgress?.(0.1 + 0.3 * (e.loaded / e.total), 'LOADING NISSAN Z…');
      });
      const scene = gltf.scene;

      // Normalise: centre on the ground, front pointing towards +Z, 4.4 m long.
      const box = new THREE.Box3().setFromObject(scene);
      const size = new THREE.Vector3();
      box.getSize(size);
      const longest = Math.max(size.x, size.z);
      if (longest > 0.01) {
        const scale = 4.38 / longest;
        scene.scale.setScalar(scale);
        box.setFromObject(scene);
      }
      const centre = new THREE.Vector3();
      box.getCenter(centre);
      scene.position.x -= centre.x;
      scene.position.z -= centre.z;
      scene.position.y -= box.min.y;
      if (size.x > size.z) scene.rotation.y = Math.PI / 2; // model was built along X

      const wheels: THREE.Object3D[] = [];
      let steeringWheel: THREE.Object3D | null = null;
      const paintMaterials: THREE.MeshStandardMaterial[] = [];

      scene.traverse((obj) => {
        const name = obj.name.toLowerCase();
        if (/wheel|tire|tyre|rim/.test(name) && !/steer/.test(name)) wheels.push(obj);
        if (/steer/.test(name)) steeringWheel = obj;
        const mesh = obj as THREE.Mesh;
        if (mesh.isMesh) {
          mesh.castShadow = true;
          mesh.receiveShadow = true;
          const mats = Array.isArray(mesh.material) ? mesh.material : [mesh.material];
          mats.forEach((m) => {
            const std = m as THREE.MeshStandardMaterial;
            if (std && /body|paint|carpaint|car_paint|lack/.test((std.name ?? '').toLowerCase())) {
              paintMaterials.push(std);
            }
          });
        }
      });

      this.onProgress?.(0.4, 'NISSAN Z LOADED');
      return { scene, wheels, steeringWheel, paintMaterials };
    } catch (err) {
      console.warn('[AssetLoader] GLB found but could not be loaded, falling back:', err);
      return null;
    }
  }

  /** Loads an optional audio file; missing files simply resolve to null. */
  async loadAudioBuffer(ctx: AudioContext, url: string): Promise<AudioBuffer | null> {
    if (!(await this.exists(url))) return null;
    try {
      const res = await fetch(url);
      const data = await res.arrayBuffer();
      return await ctx.decodeAudioData(data);
    } catch {
      return null;
    }
  }
}
